test('Changer de projet en un clic enregistre le précédent et conserve une seule minuterie', async ({ page }, testInfo) => {
  const origin = 'http://127.0.0.1:3108';
  await page.request.post(`${origin}/__test/login?id=switch-${testInfo.project.name}`);
  await page.goto(origin);
  const first = page.locator('.project').filter({ has: page.getByRole('heading', { name: 'Identité du studio', exact: true }) });
  const second = page.locator('.project').filter({ has: page.getByRole('heading', { name: 'Site du studio', exact: true }) });
  await first.getByRole('button', { name: 'Démarrer' }).click();
  await expect(page.locator('#running-time')).not.toHaveText('00:00:00');
  await expect(second.getByRole('button', { name: 'Démarrer' })).toBeEnabled();
  await second.getByRole('button', { name: 'Démarrer' }).click();
  await expect(page.locator('.timer-title')).toHaveText('Site du studio');
  await expect(page.locator('tbody .entry-project').getByText('Identité du studio', { exact: true })).toBeVisible();
  await expect(page.locator('.project.running')).toHaveCount(1);
  await expect(page.locator('#running-time')).not.toHaveText('00:00:00');
  await first.getByRole('button', { name: 'Démarrer' }).click();
  await expect(page.locator('.timer-title')).toHaveText('Identité du studio');
  await expect(page.locator('tbody .entry-project').getByText('Site du studio', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.locator('.timer-title')).toHaveText('Identité du studio');
  await expect(page.locator('.project.running')).toHaveCount(1);
  await page.getByRole('button', { name: 'Terminer', exact: true }).click();
});

