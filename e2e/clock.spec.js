test('Épingler depuis une recherche garde le filtre, affiche le projet en premier et conserve le choix', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explorer la démonstration' }).click();
  await page.getByRole('searchbox').fill('Jardins');
  await page.getByRole('button', { name: 'Épingler Campagne de lancement', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Désépingler Campagne de lancement', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('searchbox')).toHaveValue('Jardins');
  await page.getByRole('searchbox').fill('');
  await expect(page.locator('.project h3').first()).toHaveText('Campagne de lancement');
  await page.reload();
  await expect(page.locator('.project h3').first()).toHaveText('Campagne de lancement');
  await expect(page.locator('.project.pinned')).toHaveCount(1);
  await page.getByRole('button', { name: 'Épingler Identité de marque', exact: true }).click();
  await expect(page.locator('.project h3').first()).toHaveText('Identité de marque');
  await expect(page.locator('.project.pinned')).toHaveCount(2);
  await page.getByRole('button', { name: 'Désépingler Identité de marque', exact: true }).click();
  await expect(page.locator('.project h3').first()).toHaveText('Campagne de lancement');
  await page.getByRole('button', { name: 'Désépingler Campagne de lancement', exact: true }).click();
  await expect(page.locator('.project.pinned')).toHaveCount(0);
  await expect(page.locator('.project h3').first()).toHaveText('Identité de marque');
});

